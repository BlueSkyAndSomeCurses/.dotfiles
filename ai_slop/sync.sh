#!/usr/bin/env bash
# Sync global AI harness instructions and skills from this dotfiles repo.
set -euo pipefail

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)"
SOURCE_AGENTS="$SCRIPT_DIR/AGENTS.md"
SOURCE_RULES="$SCRIPT_DIR/rules"
SOURCE_SKILLS="$SCRIPT_DIR/skills"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
BACKUP_ROOT="${AI_SLOP_BACKUP_DIR:-$HOME/.ai-slop-backups}"

CHECK=0
DRIFT=0

usage() {
  cat <<'EOF'
Usage: ai_slop/sync.sh [--check]

  (no args)   Rebuild AGENTS.md, then create or repair the global symlinks.
  --check     Report missing, stale, or incorrect links and exit 1 on drift.
  -h, --help  Show this help.

Environment:
  XDG_CONFIG_HOME       Used to locate OpenCode's global config.
  AI_SLOP_BACKUP_DIR    Where replaced files are moved (default: ~/.ai-slop-backups).
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --check) CHECK=1 ;;
    -h|--help) usage; exit 0 ;;
    *)
      echo "ai_slop: unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
  shift
done

if [ ! -d "$SOURCE_RULES" ]; then
  echo "ai_slop: missing $SOURCE_RULES" >&2
  exit 1
fi

build_agents() {
  local rule found tmp
  found=0
  tmp="$(mktemp "${TMPDIR:-/tmp}/ai-slop-agents.XXXXXX")"

  {
    printf '<!-- Generated by ai_slop/sync.sh from ai_slop/rules/*.md. Do not edit this file directly. -->\n\n'
    for rule in "$SOURCE_RULES"/*.md; do
      [ -f "$rule" ] || continue
      found=1
      cat "$rule"
      printf '\n'
    done
  } > "$tmp"

  if [ "$found" -eq 0 ]; then
    rm -f "$tmp"
    echo "ai_slop: no rule files in $SOURCE_RULES" >&2
    exit 1
  fi

  if [ -f "$SOURCE_AGENTS" ] && cmp -s "$tmp" "$SOURCE_AGENTS"; then
    rm -f "$tmp"
    return 0
  fi

  if [ "$CHECK" -eq 1 ]; then
    rm -f "$tmp"
    printf 'drift:   %s (out of date)\n' "$SOURCE_AGENTS"
    DRIFT=1
    return 0
  fi

  chmod 644 "$tmp"
  mv "$tmp" "$SOURCE_AGENTS"
  printf 'build:   %s\n' "$SOURCE_AGENTS"
}

backup_target() {
  local target="$1"
  local stamp dest
  stamp="$(date +%Y%m%d-%H%M%S)"
  dest="$BACKUP_ROOT/$stamp/${target#/}"
  mkdir -p "$(dirname "$dest")"
  mv "$target" "$dest"
  printf 'backup: %s -> %s\n' "$target" "$dest"
}

link_path() {
  local source="$1"
  local target="$2"

  if [ -L "$target" ] && [ "$(readlink "$target")" = "$source" ]; then
    printf 'ok:      %s\n' "$target"
    return 0
  fi

  if [ "$CHECK" -eq 1 ]; then
    if [ -e "$target" ] || [ -L "$target" ]; then
      printf 'drift:   %s (expected -> %s)\n' "$target" "$source"
    else
      printf 'missing: %s -> %s\n' "$target" "$source"
    fi
    DRIFT=1
    return 0
  fi

  mkdir -p "$(dirname "$target")"
  if [ -e "$target" ] || [ -L "$target" ]; then
    backup_target "$target"
  fi
  ln -s "$source" "$target"
  printf 'link:    %s -> %s\n' "$target" "$source"
}

sync_skills() {
  local skill name found
  found=0

  if [ ! -d "$SOURCE_SKILLS" ]; then
    return 0
  fi

  for skill in "$SOURCE_SKILLS"/*; do
    [ -d "$skill" ] || continue
    found=1
    name="$(basename "$skill")"
    link_path "$skill" "$HOME/.agents/skills/$name"
    link_path "$skill" "$HOME/.claude/skills/$name"
  done

  if [ "$found" -eq 0 ] && [ "$CHECK" -eq 0 ]; then
    mkdir -p "$HOME/.agents/skills" "$HOME/.claude/skills"
  fi
}

build_agents

# One instructions file, three harness-specific paths. Claude Code calls it
# CLAUDE.md; OpenCode and Codex use AGENTS.md.
link_path "$SOURCE_AGENTS" "$CONFIG_HOME/opencode/AGENTS.md"
link_path "$SOURCE_AGENTS" "$HOME/.claude/CLAUDE.md"
link_path "$SOURCE_AGENTS" "$HOME/.codex/AGENTS.md"

# Link skills one by one so tool-managed skills (for example orx's shim) survive.
sync_skills

if [ -f "$HOME/.codex/AGENTS.override.md" ]; then
  printf 'warning: %s exists and takes precedence over ~/.codex/AGENTS.md\n' \
    "$HOME/.codex/AGENTS.override.md" >&2
fi

if [ "$CHECK" -eq 1 ]; then
  if [ "$DRIFT" -eq 1 ]; then
    echo "ai_slop: drift detected; run $SCRIPT_DIR/sync.sh" >&2
    exit 1
  fi
  echo "ai_slop: generated file and links are up to date"
fi
